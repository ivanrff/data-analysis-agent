marked.setOptions({
    highlight: function(code, lang) {
        if (lang && hljs.getLanguage(lang)) {
            return hljs.highlight(code, { language: lang }).value;
        }
        return hljs.highlightAuto(code).value;
    },
    breaks: true // Converts line breaks \n into <br> tags
});

let currentSessionId = sessionStorage.getItem('chatSessionId');

if (!currentSessionId) {
    // Generate a random string to serve as a unique session identifier
    currentSessionId = 'session_' + Math.random().toString(36).substring(2, 15);
    sessionStorage.setItem('chatSessionId', currentSessionId);
}

// Async function to send the user message and process the AI response
async function send() {
    const input = document.getElementById("msg");
    const userMessage = input.value.trim();

    if (!userMessage) return;

    appendMessage("Você", userMessage, "user-msg");
    input.value = "";

    // Create initial AI bubble indicating loading state
    const loadingDiv = appendMessage("AI", "Pensando...", "ai-msg", "loading");
    
    try {
        const res = await fetch("/chat", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ message: userMessage, session_id: currentSessionId})
        });

        if (res.status === 429) {
            throw new Error("Limite de interações atingido. Esse site é apenas para testes rápidos.");
        }
        
        if (!res.ok) throw new Error("Erro de conexão com o servidor.");

        const reader = res.body.getReader();
        const decoder = new TextDecoder("utf-8");
        
        let isFirstChunk = true;
        let rawText = "";

        while (true) {
            const { value, done } = await reader.read();
            if (done) break;

            const chunk = decoder.decode(value, { stream: true });

            if (isFirstChunk) {
                loadingDiv.classList.remove("loading");
                isFirstChunk = false;
            }

            rawText += chunk;

            // Render Markdown directly into HTML
            loadingDiv.innerHTML = marked.parse(rawText);

            // Re-apply highlight to code blocks created during streaming
            // loadingDiv.querySelectorAll('pre code').forEach((block) => {
            //     hljs.highlightElement(block);
            // });

            const chat = document.getElementById("chat");
            chat.scrollTop = chat.scrollHeight;
        }

        renderCharts(loadingDiv);

    } catch (error) {
        loadingDiv.textContent = error.message;
        loadingDiv.classList.remove("loading");
        loadingDiv.classList.add("error-msg");
    }
}

// Helper function to create chat bubbles
function appendMessage(sender, text, ...classNames) {
    const chat = document.getElementById("chat");
    const msgDiv = document.createElement("div");

    msgDiv.classList.add("chat-bubble");
    
    classNames.forEach(cls => {
        cls.split(" ").filter(Boolean).forEach(c => msgDiv.classList.add(c));
    });

    // Handle initial rendering (Markdown for text or plain text fallback)
    msgDiv.innerHTML = marked.parse(text);
    
    chat.appendChild(msgDiv);
    chat.scrollTop = chat.scrollHeight;

    return msgDiv; 
}

// Function to find the json-chart blocks and render them
// app/static/chat.js

function renderCharts(messageElement) {
    // Find all code blocks with the json-chart language
    const codeBlocks = messageElement.querySelectorAll('code.language-json-chart');
    
    // If charts exist, expand the chat bubble
    if (codeBlocks.length > 0) {
        messageElement.classList.add('has-chart');
    }
    
    codeBlocks.forEach((block, index) => {
        try {
            // Parse the JSON configuration generated by the LLM
            const chartConfig = JSON.parse(block.textContent);
            
            // Create a container div for Plotly
            const chartId = 'chart_' + Date.now() + '_' + index;
            const chartContainer = document.createElement('div');
            chartContainer.id = chartId;
            chartContainer.className = 'chart-wrapper'; 
            
            // Replace the markdown code block with the new container
            block.parentElement.replaceWith(chartContainer);
            
            // Define default layout settings to optimize space inside the chat bubble
            const defaultLayout = {
                margin: { l: 40, r: 20, t: 40, b: 40 }, // Reduces outer whitespace
                paper_bgcolor: 'transparent',
                plot_bgcolor: 'transparent',
                font: { size: 12 }
            };
            
            // Merge default layout with any specific layout provided by the LLM
            const finalLayout = Object.assign({}, defaultLayout, chartConfig.layout);
            
            // Render the chart
            Plotly.newPlot(
                chartId, 
                chartConfig.data, 
                finalLayout, 
                { responsive: true, displayModeBar: false } 
            );
            
        } catch (error) {
            console.error("Failed to parse chart JSON:", error);
        }
    });
}

// Allow pressing "Enter" to trigger the send function
document.getElementById("msg").addEventListener("keypress", function(event) {
    if (event.key === "Enter") {
        event.preventDefault();
        send();
    }
});